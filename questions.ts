/**
 * Fisher-Yates shuffle algorithm
 */
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Creates a randomized game session of 10 questions:
 * 3 easy, 4 medium, 3 hard questions,
 * and within each question shuffles all 4 answer options!
 */
export function generateRandomizedQuiz(questionCount = 10): ShuffledQuestion[] {
  const easyQuestions = shuffleArray(QUESTION_BANK.filter(q => q.difficulty === 'easy'));
  const mediumQuestions = shuffleArray(QUESTION_BANK.filter(q => q.difficulty === 'medium'));
  const hardQuestions = shuffleArray(QUESTION_BANK.filter(q => q.difficulty === 'hard'));

  // Select 3 easy, 4 medium, 3 hard (total 10)
  const selected: RawQuestion[] = [
    ...easyQuestions.slice(0, 3),
    ...mediumQuestions.slice(0, 4),
    ...hardQuestions.slice(0, 3)
  ];

  // Shuffle the questions order so each play is varied
  const shuffledQuestions = shuffleArray(selected);

  // Now for each question, shuffle options and compute the new correctIndex
  return shuffledQuestions.map(q => {
    const correctOptionText = q.options[q.correctIndex];
    const shuffledOptions = shuffleArray(q.options);
    const newCorrectIndex = shuffledOptions.indexOf(correctOptionText);

    return {
      id: q.id,
      topic: q.topic,
      difficulty: q.difficulty,
      question: q.question,
      options: shuffledOptions,
      correctIndex: newCorrectIndex,
      originalCorrectText: correctOptionText,
      explanation: q.explanation,
      illustrationType: q.illustrationType
    };
  });
}
